'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {smf,tempo}=require('./midi.cjs'),{parse}=require('../engine/midi.cjs'),{normalize}=require('../engine/normalize.cjs');
const bytes=smf([[tempo(0,500000),[0,192,0],...[84,88,92,96].flatMap((p,i)=>[[i*360,144,p,100],[i*360+120,128,p,0]])]]);
const raw=parse(bytes),before=JSON.stringify(raw),base={target:'26.1.2',soundEngine:'vanilla'};
assert.throws(()=>normalize(raw,{...base,pitch:'strict'}),/超出原版/);
const smart=normalize(raw,{...base,pitch:'smart'}),fold=normalize(raw,{...base,pitch:'fold'});
const delta=ns=>ns.slice(1).map((n,i)=>n.key-ns[i].key);
assert.deepEqual(delta(smart.notes),[4,4,4]);assert.notDeepEqual(delta(fold.notes),[4,4,4]);
assert.equal(smart.midiConversion.vanillaFit.residualFoldedNotes,0);
assert(smart.notes.every(n=>n.key>=33&&n.key<=57));
assert.deepEqual(smart.notes.map(n=>n.tick),fold.notes.map(n=>n.tick));
assert(smart.notes.every((n,i)=>(n.key-raw.notes[i].key)%12===0));
assert.equal(JSON.stringify(raw),before,'never mutate source notes or mapping');
const enb=normalize(raw,{...base,soundEngine:'extended',pitch:'smart'});
assert.deepEqual(enb.notes.map(n=>n.key),raw.notes.map(n=>n.key));
assert(!enb.midiConversion.vanillaFit);
const broad={...raw,notes:[...raw.notes,{...raw.notes[0],key:4},{...raw.notes[0]}]};
const wide=normalize(broad,{...base,pitch:'smart',transpose:1});
assert.equal(wide.notes.length,broad.notes.length,'preserve duplicate source notes');
assert(wide.notes.every(n=>n.key>=33&&n.key<=57));assert(wide.midiConversion.vanillaFit.residualFoldedNotes>0);
const nbs={...raw,sourceType:'nbs'};assert.throws(()=>normalize(nbs,{...base,pitch:'smart'}),/超出原版/);
const dir=path.resolve('tests/output/midi-vanilla-fit');fs.mkdirSync(dir,{recursive:true});
const input=path.join(dir,'high-part.mid');fs.writeFileSync(input,bytes);
const result=require('../engine/cli.cjs').convert({...base,pitch:'smart',input,output:dir,objective:'toxic'},()=>{});
assert.equal(result.notes,4);assert(!result.extendedNoteblock);
fs.writeFileSync(path.join(dir,'verification.json'),JSON.stringify({pass:true,schematic:result.schematic,smart:smart.midiConversion.vanillaFit,foldedKeys:fold.notes.map(n=>n.key),smartKeys:smart.notes.map(n=>n.key)},null,2));
console.log('PASS vanilla MIDI: per-part octaves preserve melodic intervals, pitch classes, onsets and duplicates; strict/NBS/ENB policies unchanged; actual vanilla export');

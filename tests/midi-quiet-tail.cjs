'use strict';
const assert=require('node:assert/strict');
const {finishQuietTail}=require('../engine/midi-adaptive-envelope.cjs');
const points=values=>values.map((v,i)=>({t:i/Math.max(1,values.length-1),v}));
const falling=points([1,.5,.2,.11,.105,...Array(40).fill(.08),0]);
const tail=finishQuietTail(falling);
assert.equal(tail.info.startTick,4,'strictly below .11, not equal');
assert.equal(tail.info.fadeTicks,5);assert.equal(tail.points.length,10);
assert.equal(tail.points[4].v,.105,'no step at start of fade');
assert.equal(tail.points.at(-1).v,0);
assert(tail.points.every((p,i)=>p.v<=falling[i].v&&(!i||p.v<=tail.points[i-1].v)));
assert.equal(falling[9].v,.08,'input curve is not mutated');
assert.equal(finishQuietTail(points([0,.02,.06,.10,.2,.5,1]),6).info,null,'attack is preserved');
assert.equal(finishQuietTail(points([.11,.11,.11,0])).info,null,'threshold is exclusive');
assert.equal(finishQuietTail(points([.08,.08,.08,0])).info,null,'quiet steady notes are not mistaken for a tail');
const crescendo=points([.5,.1,.08,.08,.09,.2,.5,.2,.1,.05,.02,0]);
const guarded=finishQuietTail(crescendo);
assert.equal(guarded.info.startTick,8,'later MIDI crescendo is preserved');
assert.deepEqual(guarded.points.slice(0,8),crescendo.slice(0,8));
assert.equal(guarded.info.fadeTicks,3,'short release is never extended');
const {smf,tempo}=require('./midi.cjs');
const {parse}=require('../engine/midi.cjs'),{plan}=require('../engine/adaptive.cjs'),{normalize}=require('../engine/normalize.cjs');
const raw=parse(smf([[tempo(0,500000),[0,192,0],[0,144,60,100],[4800,128,60,64]]]));
const opt=plan(raw,{adaptive:true,target:'26.1.2',soundEngine:'extended',midiEnvelope:'adaptive'}).options;
const n=normalize(raw,opt).notes[0],manual=normalize(raw,{...opt,midiEnvelope:'custom',midiFadeOutMs:50}).notes[0];
assert(n.enbSustainTime<n.midiEnvelopeInfo.gateTicks,'quiet piano tail releases its channel before long gate ends');
assert.equal(n.enbSustainTime,n.midiEnvelopeInfo.quietTail.endTick+1);
assert.equal(n.enbVolumePoints.at(-1).v,0);assert.equal(n.enbVolumePoints.at(-1).t,1);
assert.equal(n.midiEnvelopeInfo.quietTail.originalDurationTicks,n.midiEnvelopeInfo.gateTicks+n.midiEnvelopeInfo.releaseTicks);
assert.equal(manual.enbVolumePoints,undefined,'manual envelope unchanged');assert(manual.enbSustainTime>n.enbSustainTime);
assert.equal(manual.tick,n.tick,'onset unchanged');assert.equal(manual.key,n.key,'pitch unchanged');
console.log('PASS quiet tails: strict 0.11, smooth 5-tick finish, shortened lifetime, attack/crescendo protection, short release and manual mode');

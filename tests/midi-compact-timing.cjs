'use strict';
const assert=require('node:assert/strict');
const {smf,tempo}=require('./midi.cjs'),{parse}=require('../engine/midi.cjs');
const {plan,mapTick}=require('../engine/midi-timing.cjs'),{normalize}=require('../engine/normalize.cjs');
const {encode}=require('./enb-fixture.cjs');
const starts=[...Array.from({length:1000},(_,i)=>i*96),4896+48].sort((a,b)=>a-b);
const bytes=smf([[tempo(0,500000),...starts.flatMap(t=>[[t,144,60,100],[t+1,128,60,0]]).sort((a,b)=>a[0]-b[0])]]);
const raw=parse(bytes),original=JSON.stringify(raw),compact=plan(raw),precise=plan(raw,{midiPrefer10t:false});
assert.equal(precise.resolution,20);assert(precise.exact);
assert.equal(compact.resolution,10);assert(compact.compactTiming.selected);
assert.equal(compact.onsetsAbove25Ms,1);assert(compact.distinctOnsetRmsMs<2);
assert.equal(plan(raw,{midiTimingMode:'strict'}).resolution,20,'strict mode may not introduce quantization');
assert.equal(plan(raw,{midiAutoResolution:false,timeResolution:20}).resolution,20);
assert.equal(plan(raw,{midiAutoResolution:false,timeResolution:10}).resolution,10);
assert.deepEqual(compact.segments.map(s=>s.speedFactor),[1]);
const options={target:'26.1.2',soundEngine:'vanilla',pitch:'strict',timeResolution:10,midiPlan:compact};
const song=normalize(raw,options);assert.equal(song.notes.length,raw.notes.length);
const clone=require('../engine/nbs.cjs').parse(encode(song.notes.map((n,i)=>({...n,tick:n.tick,layer:i})),{tempo:10}));
const nbs=normalize(clone,{...options,midiPlan:undefined,timing:'strict'});
const signature=s=>s.notes.map(n=>[n.tick,n.key,n.instrument].join()).sort();
assert.deepEqual(signature(song),signature(nbs),'same mapped events have the same geometry input, regardless of format');
assert.equal(JSON.stringify(raw),original,'source must not be changed');
const dense=Array.from({length:300},(_,i)=>i*120),fast=parse(smf([[tempo(0,500000),...dense.flatMap(t=>[[t,144,60,100],[t+1,128,60,0]]).sort((a,b)=>a[0]-b[0])]]));
assert.equal(plan(fast).resolution,20,'regular sixteenth notes must not be coarsened to 10t');
assert(!plan(fast).compactTiming.selected);
// A very large chord may not mask repeated 50ms changes to a sparse melody.
const many=[...Array.from({length:1000},(_,i)=>[0,144,40+i%40,100]),...Array.from({length:30},(_,i)=>[(i*2+1)*48,144,70,100])].sort((a,b)=>a[0]-b[0]);
const uneven=parse(smf([[tempo(0,500000),...many]]));assert.equal(plan(uneven).resolution,20);
assert(starts.every((t,i)=>song.notes[i].tick===mapTick(t,compact)));
console.log('PASS compact MIDI timing: rare off-grid notes use 10t, fast passages stay 20t, strict/fixed/precision controls, no lost notes, same MIDI/NBS geometry input');
